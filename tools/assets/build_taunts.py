#!/usr/bin/env python3
"""Bundle pinned taunt recordings and their mouth envelopes."""

import argparse
import hashlib
import json
from pathlib import Path
import shutil
import sys

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parent))
import build_head


def dry_mouth(entry, frames):
    """A mixed clip moves his mouth with its dry voice line, so the bed under it stays out."""
    root = Path(__file__).resolve().parents[2]
    dry = build_head.decode_mono(str(root / "voice-lines" / entry["mouth_source"]), 0, entry["millis"] / 1000, build_head.MOUTH_RATE)
    delay = entry["mouth_delay_millis"] * build_head.MOUTH_RATE // 1000
    audio = np.concatenate([np.zeros(delay), dry])[:entry["millis"] * build_head.MOUTH_RATE // 1000]
    return (build_head.mouth_envelope(audio, build_head.MOUTH_RATE) + [0] * frames)[:frames]


def build(source, manifest="taunts.json", prefix="taunt", class_name="TauntVoice"):
    entries = json.loads(Path(__file__).with_name(manifest).read_text())
    verified = []
    for entry in entries:
        path = source / (entry["id"] + ".ogg")
        if hashlib.sha256(path.read_bytes()).hexdigest() != entry["sha256"]:
            raise ValueError("source hash mismatch: " + entry["id"])
        verified.append((entry, path))
    lines = ["// generated by build_taunts.py, do not edit",
             "package com.larsoyd.mariohead.entity;", "", f"public final class {class_name} {{",
             "\tpublic static final HeadVoice.Clip[] CLIPS = {"]
    for entry, path in verified:
        name = prefix + "_" + entry["id"].split("_")[0]
        audio = build_head.decode_mono(str(path), 0, entry["millis"] / 1000, build_head.MOUTH_RATE)
        mouth = build_head.mouth_envelope(audio, build_head.MOUTH_RATE)
        if "mouth_source" in entry:
            mouth = dry_mouth(entry, len(mouth))
        if "mouth_end_millis" in entry:
            end = entry["mouth_end_millis"] * build_head.MOUTH_FPS // 1000
            mouth[end:] = [0] * (len(mouth) - end)
        lines.append(f'\t\tnew HeadVoice.Clip("{name}", {entry["millis"]}, new int[] {{')
        for start in range(0, len(mouth), 24):
            lines.append("\t\t\t" + ", ".join(map(str, mouth[start:start + 24])) + ("," if start + 24 < len(mouth) else ""))
        lines.append("\t\t}),")
        shutil.copyfile(path, Path(build_head.SOUND_DIR) / (name + ".ogg"))
    lines.extend(["\t};", "", f"\tprivate {class_name}() {{", "\t}", "}", ""])
    (Path(build_head.JAVA_DIR) / (class_name + ".java")).write_text("\n".join(lines))


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("source", type=Path, help="directory containing the pinned OGG clips")
    build(parser.parse_args().source)
