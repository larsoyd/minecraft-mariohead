#!/usr/bin/env python3
"""Bundle home dialogue with the FilmCraft return-line mix."""

import argparse
import hashlib
import json
from pathlib import Path
import shutil
import sys

sys.path.insert(0, str(Path(__file__).resolve().parent))
import build_head


def verify(path, digest):
    if hashlib.sha256(path.read_bytes()).hexdigest() != digest:
        raise ValueError('source hash mismatch: ' + str(path))


def build(source, mix):
    entries = json.loads(Path(__file__).with_name('home-lines.json').read_text())
    for entry in entries:
        verify(source / (entry['id'] + '.ogg'), entry['sha256'])
    edited = entries[-1]
    verify(source / (edited['donor_id'] + '.ogg'), edited['donor_sha256'])
    verify(mix, edited['mixed_sha256'])
    lines = ['// generated by build_home_voice.py, do not edit',
             'package com.larsoyd.mariohead.entity;', '', 'public final class HomeVoice {',
             '\tpublic static final HeadVoice.Clip[] CLIPS = {']
    for entry in entries:
        name = 'home_' + entry['id'][:3]
        path = mix if 'mixed_sha256' in entry else source / (entry['id'] + '.ogg')
        millis = entry.get('mixed_millis', entry['millis'])
        samples = build_head.decode_mono(str(path), 0, millis / 1000, build_head.MOUTH_RATE)
        mouth = build_head.mouth_envelope(samples, build_head.MOUTH_RATE)
        lines.append(f'\t\tnew HeadVoice.Clip("{name}", {millis}, new int[] {{')
        for start in range(0, len(mouth), 24):
            lines.append('\t\t\t' + ', '.join(map(str, mouth[start:start + 24]))
                         + (',' if start + 24 < len(mouth) else ''))
        lines.append('\t\t}),')
        dest = Path(build_head.SOUND_DIR) / (name + '.ogg')
        if path.resolve() != dest.resolve():
            shutil.copyfile(path, dest)
    lines.extend(['\t};', '', '\tprivate HomeVoice() {', '\t}', '}', ''])
    (Path(build_head.JAVA_DIR) / 'HomeVoice.java').write_text('\n'.join(lines))


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('source', type=Path)
    parser.add_argument('mix', type=Path)
    args = parser.parse_args()
    build(args.source, args.mix)
